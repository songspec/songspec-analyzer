#!/usr/bin/env python3
"""Regenerate service/songspec_analyzer/tempo/_bpmfix_port.py from BPM Fixer's app/bpmfix.py.

The analysis half of BPM Fixer is copied VERBATIM (function by function, via the ast module) so that its hard-won logic cannot
drift; the service adds its own wrapper in tempo/engine.py. Re-run this when bpmfix.py changes, then run the parity tests.
Run:  .venv/Scripts/python tools/port_bpmfix.py  ["path/to/bpmfix.py"]
"""
import ast
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "Everything Claude Needs" / "BPM-Fixer-source" / "bpm-fixer" / "app" / "bpmfix.py"
OUT = ROOT / "service" / "songspec_analyzer" / "tempo" / "_bpmfix_port.py"
OUT_FIX = ROOT / "service" / "songspec_analyzer" / "tempo" / "_bpmfix_fix.py"

# the second file: BPM Fixer's process() and everything it needs beyond the analysis (stretching, level, saving)
FIX_CONSTANTS = ["DEFAULTS", "AUDIO_EXTS", "EXPORT_FORMATS", "LOSSY"]
FIX_FUNCTIONS = ["app_dir", "find_ffmpeg", "load_audio", "save_audio", "_db", "limit_peaks", "match_level", "build_timemap",
                 "splice_edges", "find_rubberband", "stretch_cli", "stretch_pylibrb", "time_stretch", "write_click_check",
                 "process"]

CONSTANTS = ["HOP", "TIME_SIGNATURES", "BPM_MODES", "LEVEL_MULTS", "ALLOWED_RATIOS", "WRONG_LEVEL", "RISE_FRAC"]
FUNCTIONS = [
    # meter + metrical level
    "sig_spec", "anchor_q", "period_to_bpm", "bpm_to_period", "infer_signature", "_log_mode", "level_reference",
    "choose_level", "_pll", "_start_index", "clean_sequence", "summarize_events", "_circular_period", "bars_reference",
    "anchors_from_bars", "prepare_anchors",
    # level guard
    "_rolling_median", "_wmedian", "pick_reference_period", "find_bad_runs", "onset_env", "retrack_region", "_tidy",
    "enforce_level",
    # refinement + stats
    "_window_env", "_pick_peak", "_windows", "refine_beats", "fill_weak_runs", "grid_alignment", "measure_offset",
    "irregularity", "fmt_bpm", "stretch_report",
]


def main():
    src_path = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC
    text = src_path.read_text(encoding="utf-8")
    lines = text.splitlines()
    tree = ast.parse(text)
    found = {}
    whole = lambda node: "\n".join(lines[node.lineno - 1:node.end_lineno])     # whole lines: keeps trailing comments
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in FUNCTIONS:
            found[node.name] = whole(node)
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) \
                and node.targets[0].id in CONSTANTS:
            found[node.targets[0].id] = whole(node)
    missing = [n for n in CONSTANTS + FUNCTIONS if n not in found]
    if missing:
        raise SystemExit(f"not found in {src_path}: {missing}")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    parts = [
        '"""GENERATED by tools/port_bpmfix.py - do not edit by hand.',
        "",
        "Verbatim copy of the analysis functions of BPM Fixer's app/bpmfix.py (beat cleaning, metrical level, time signature,",
        "level guard, beat refinement, tempo statistics). The service's own code is in tempo/engine.py.",
        f"Source SHA-256: {digest}",
        '"""',
        "# flake8: noqa",
        "import numpy as np",
        "import librosa",
        "",
    ]
    for n in CONSTANTS:
        parts += [found[n], ""]
    for n in FUNCTIONS:
        parts += ["", found[n], ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(FUNCTIONS)} functions, {len(CONSTANTS)} constants) from {src_path}")

    # ---- the Fix BPM file
    fix = {}
    pylibrb_block = None
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name in FIX_FUNCTIONS:
            fix[node.name] = whole(node)
        elif isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) \
                and node.targets[0].id in FIX_CONSTANTS:
            fix[node.targets[0].id] = whole(node)
        elif isinstance(node, ast.Try) and "pylibrb" in whole(node):
            pylibrb_block = whole(node)
    missing = [n for n in FIX_CONSTANTS + FIX_FUNCTIONS if n not in fix] + ([] if pylibrb_block else ["pylibrb import"])
    if missing:
        raise SystemExit(f"not found in {src_path}: {missing}")
    parts = [
        '"""GENERATED by tools/port_bpmfix.py - do not edit by hand.',
        "",
        "Verbatim copy of BPM Fixer's process() (app/bpmfix.py) and the functions it needs beyond the analysis: time map, Rubber Band",
        "stretching, intro / outro splicing, loudness matching, saving. The service supplies `detect_beats` (Beat This! with the",
        "vendored model) and `find_rubberband` (its configured binary) by assigning them on this module (tempo/fixbpm.py).",
        f"Source SHA-256: {digest}",
        '"""',
        "# flake8: noqa",
        "import os",
        "import shutil",
        "import subprocess",
        "import sys",
        "import tempfile",
        "",
        "import numpy as np",
        "import librosa",
        "import soundfile as sf",
        "",
        "from ._bpmfix_port import *",
        "from ._bpmfix_port import HOP",
        "",
        pylibrb_block,
        "",
        "detect_beats = None      # assigned by tempo/fixbpm.py",
        "",
    ]
    for n in FIX_CONSTANTS:
        parts += [fix[n], ""]
    for n in FIX_FUNCTIONS:
        parts += ["", fix[n], ""]
    OUT_FIX.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT_FIX} ({len(FIX_FUNCTIONS)} functions, {len(FIX_CONSTANTS)} constants)")


if __name__ == "__main__":
    main()
